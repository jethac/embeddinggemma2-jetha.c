int main(void) {
    unsigned char *rgb = NULL;
    int width = 0, height = 0;
    CHECK(ei_jpeg_decode2(image, sizeof image, 1024, 4096, &rgb, &width, &height) == 1);
    CHECK(rgb && width == 32 && height == 24);
    for (size_t i = 0; i < 32 * 24 * 3; i++) CHECK(rgb[i] == 42);
    free(rgb);
    CHECK(ei_jpeg_decode2(image, sizeof image, 100, 4096, &rgb, &width, &height) == -1 && !rgb);
    CHECK(ei_jpeg_decode2(image, sizeof image, 1024, 100, &rgb, &width, &height) == -1 && !rgb);
    CHECK(ei_jpeg_decode2(image, 10, 1024, 4096, &rgb, &width, &height) == -1 && !rgb);
    CHECK(ei_jpeg_decode2((const unsigned char *)"PNG", 3, 1024, 4096, &rgb, &width, &height) == 0 && !rgb);
    unsigned char oversized[sizeof image];
    memcpy(oversized, image, sizeof image);
    size_t sof = 0;
    for (size_t i = 0; i + 9 < sizeof image; i++)
        if (image[i] == 0xff && image[i + 1] == 0xc0) { sof = i; break; }
    CHECK(sof);
    memset(oversized + sof + 5, 0xff, 4);
    CHECK(ei_jpeg_decode2(oversized, sizeof oversized, 16777216, 128u * 1024u * 1024u, &rgb, &width, &height) == -1 && !rgb);
    puts("JPEG decoding, malformed input and pixel/byte limits: passed");
    return 0;
}
